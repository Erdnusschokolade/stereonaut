#ifndef STEREONAUT_JELLYFIN_H
#define STEREONAUT_JELLYFIN_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* Blocking Jellyfin REST client (libcurl + json-c). Every call may take
 * seconds; callers run it on a worker thread. Error strings are German and
 * shown in the browser. */

#define JF_ID_SIZE 48
#define JF_AUTH_RETRY (-2) /* token missing, expired or rejected */
#define JF_BROKEN_ITEM (-3) /* the server's file has no video stream */

struct jf_config {
    char server[256];
    char device_id[64];
    char user_id[64];
    char token[256];
};

struct jf_item {
    char id[JF_ID_SIZE];
    char name[256];
    bool is_folder;
    /* Image path below /Items/ID/Images/ for landscape tiles: the backdrop,
     * then "|" and the primary image (poster) as fallback for backdrops
     * that are a small picture on a plain square; one of them alone if the
     * other is missing, "" if neither exists. */
    char image[160];
    int64_t runtime_ticks; /* 0 if unknown; 10 000 000 ticks per second */
    int year;              /* 0 if unknown */
    char codec[32];        /* first video stream, e.g. "HEVC Main 10" ("" if unknown) */
    int width, height;     /* first video stream, 0 if unknown */
    /* The user's state: resume position (0 = from the start), share
     * watched in percent and whether it was played to the end. */
    int64_t resume_ticks;
    float played_percentage;
    bool played;
};

struct jf_playback {
    char url[2304];
    char item_id[JF_ID_SIZE];
    char media_source[JF_ID_SIZE];
    char play_session[128];
    bool transcoding;
    /* For format detection: the source's file name (or its name if the
     * server hides paths) and Video3DFormat ("" if unset). */
    char file_name[256];
    char video_3d_format[32];
};

/* Playback state reports: the dashboard's "now playing", webhooks on the
 * server and the resume position all depend on them. */
enum jf_report {
    JF_REPORT_START,
    JF_REPORT_PROGRESS,
    JF_REPORT_STOPPED,
};

/* Scrub previews (trickplay) generated by the server: tile images holding
 * `columns` x `rows` thumbnails, one every `interval_ms`. */
struct jf_trickplay {
    char media_source[JF_ID_SIZE];
    int width, height; /* one thumbnail */
    int columns, rows;
    int count;
    int interval_ms;
};

/* Description of a title for the player: chapters (seek bar marks) and the
 * information tab. Lists are comma separated, cut to fit. */
#define JF_MAX_CHAPTERS 64
struct jf_details {
    char overview[1536];
    char people[256];
    char studios[160];
    char genres[160];
    char tags[256];
    float community_rating; /* 0 if unknown */
    int year;               /* 0 if unknown */
    int chapter_count;
    int64_t chapter_us[JF_MAX_CHAPTERS];
    char chapter_names[JF_MAX_CHAPTERS][48];
};

/* Reads $XDG_CONFIG_HOME/stereonaut/jellyfin.json. Returns 0 if a server is
 * configured (token may still be empty), -1 otherwise. */
int jf_config_load(struct jf_config *config, char *error, size_t error_size);
bool jf_config_has_token(const struct jf_config *config);

/* Quick Connect: start returns the code to show and a secret to poll with.
 * Poll sets *authenticated and, on success, stores the token on disk. */
int jf_quickconnect_start(struct jf_config *config, char code[16],
                          char secret[128], char *error, size_t error_size);
int jf_quickconnect_poll(struct jf_config *config, const char *secret,
                         bool *authenticated, char *error, size_t error_size);

/* Sort criteria of a folder listing (server side; same order as the menu). */
enum jf_sort {
    JF_SORT_NAME,
    JF_SORT_RANDOM,
    JF_SORT_COMMUNITY_RATING,
    JF_SORT_CRITIC_RATING,
    JF_SORT_DATE_ADDED,
    JF_SORT_DATE_PLAYED,
    JF_SORT_OFFICIAL_RATING,
    JF_SORT_PLAY_COUNT,
    JF_SORT_PREMIERE_DATE,
    JF_SORT_RUNTIME,
    JF_SORT_COUNT,
};

/* Filters of a library listing: titles of one genre, studio or person. */
enum jf_filter {
    JF_FILTER_NONE,
    JF_FILTER_GENRE,
    JF_FILTER_STUDIO,
    JF_FILTER_PERSON,
    JF_FILTER_COUNT,
};

/* Libraries (views) sorted by name and the children of a folder in the given
 * order (folders first); with a filter all titles below the folder that
 * match it. The array is freed with free(). */
int jf_list_views(const struct jf_config *config, struct jf_item **items,
                  size_t *count, char *error, size_t error_size);
int jf_list_children(const struct jf_config *config, const char *parent_id,
                     enum jf_filter filter, const char *filter_id,
                     enum jf_sort sort, bool descending,
                     struct jf_item **items, size_t *count,
                     char *error, size_t error_size);
/* The genres, studios or persons occurring below a folder, by name. */
int jf_list_filter_values(const struct jf_config *config,
                          const char *parent_id, enum jf_filter filter,
                          struct jf_item **items, size_t *count,
                          char *error, size_t error_size);
/* Partly watched videos of all libraries, most recent first ("continue
 * watching"); a short timeout, the start page waits for it. */
int jf_list_resume(const struct jf_config *config, struct jf_item **items,
                   size_t *count, char *error, size_t error_size);
/* Name and parent id of an item (parent may be empty). */
int jf_item_info(const struct jf_config *config, const char *id,
                 char *name, size_t name_size, char *parent,
                 size_t parent_size, char *error, size_t error_size);

/* Chooses Direct Play for HEVC Main 8 bit in mkv/mp4 and an HLS transcode to
 * HEVC Main 8 bit otherwise. The URL carries no credentials. */
int jf_resolve_playback(const struct jf_config *config, const char *item_id,
                        struct jf_playback *playback, char *error,
                        size_t error_size);
/* Downloads an item image (`image` as in jf_item) scaled to `max_width`.
 * On success *data is malloc'd and owned by the caller. */
int jf_fetch_image(const struct jf_config *config, const char *item_id,
                   const char *image, int max_width, char **data,
                   size_t *size);
/* Stops the server-side transcode of a finished or restarted playback. */
void jf_stop_encoding(const struct jf_config *config,
                      const struct jf_playback *playback);
/* Posts /Sessions/Playing[/Progress|/Stopped]. `event` is the optional
 * EventName of a progress report ("pause", "unpause", "timeupdate"). */
int jf_report_playback(const struct jf_config *config,
                       const struct jf_playback *playback,
                       enum jf_report report, int64_t position_us,
                       bool paused, const char *event);
/* Trickplay description of an item (largest width up to 640 px); -1 if the
 * server has none. */
int jf_trickplay_info(const struct jf_config *config, const char *item_id,
                      struct jf_trickplay *info);
int jf_item_details(const struct jf_config *config, const char *item_id,
                    struct jf_details *details);
/* Downloads tile image `tile` (JPEG); *data is malloc'd. */
int jf_fetch_trickplay_tile(const struct jf_config *config,
                            const char *item_id,
                            const struct jf_trickplay *info, int tile,
                            char **data, size_t *size);
/* "Authorization: MediaBrowser ..." line for STEREONAUT_HTTP_HEADERS. */
void jf_authorization_header(const struct jf_config *config, char *out,
                             size_t out_size);

#endif
